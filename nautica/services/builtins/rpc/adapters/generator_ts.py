from .....models.Rpc import RPCNamespace, RPCFunc, RPCArg

import json
import types
import typing
from typing import Any

_PRIMITIVES = {
    bool: "boolean",
    int: "number",
    float: "number",
    str: "string",
    type(None): "null",
    None: "null",
}

def pyToTs(t) -> str:
    """Converts a Python type hint into a TypeScript type, anything not representable in JSON becomes 'any'"""
    if t is Any: return "any"
    if t in _PRIMITIVES: return _PRIMITIVES[t]

    origin = typing.get_origin(t)
    params = typing.get_args(t)

    if origin in (typing.Union, types.UnionType):
        return " | ".join(dict.fromkeys(pyToTs(p) for p in params))

    if origin is typing.Literal:
        return " | ".join(json.dumps(p) for p in params)

    if t in (list, set, frozenset, tuple) or origin in (list, set, frozenset):
        return f"Array<{pyToTs(params[0]) if params else 'any'}>"

    if origin is tuple:
        if len(params) == 2 and params[1] is Ellipsis: return f"Array<{pyToTs(params[0])}>"
        return "[" + ", ".join(pyToTs(p) for p in params) + "]"

    if t is dict: return "Record<string, any>"
    if origin is dict: return f"Record<string, {pyToTs(params[1])}>"

    return "any"

def _argType(arg: RPCArg) -> str:
    #unannotated args with a default value take the default's type
    if arg.type is Any and arg.default is not None: return pyToTs(type(arg.default))
    return pyToTs(arg.type)

def _funcSignature(fn: RPCFunc) -> str:
    fields = [f"{a.name}: {_argType(a)}" for a in fn.args]
    fields += [f"{a.name}?: {_argType(a)}" for a in fn.kwargs]

    #params can be omitted entirely when nothing is required
    params = f"params{'' if fn.args else '?'}: {{ {'; '.join(fields)} }}" if fields else ""
    return f"{fn.name}({params}): Promise<{pyToTs(fn.type_hint)}>;"

def generate(namespaces: dict[str, RPCNamespace]) -> str:
    """Generates a typed TypeScript client for all registered RPC namespaces"""
    interface = []
    schema = {}

    for ns in sorted(namespaces.values(), key=lambda n: n.name):
        interface.append(f"    {ns.name}: {{")
        for fn in ns.funcs:
            interface.append(f"        {_funcSignature(fn)}")
        interface.append("    };")

        #names of positional args, everything else gets sent as kwargs
        schema[ns.name] = {fn.name: [a.name for a in fn.args] for fn in ns.funcs}

    return (_TEMPLATE
        .replace("%INTERFACE%", "\n".join(interface))
        .replace("%SCHEMA%", json.dumps(schema, indent=4))
    )

_TEMPLATE = """// Generated by Nautica, do not edit by hand

export interface RPCNamespaces {
%INTERFACE%
}

export type RPCClient = NauticaRPC & RPCNamespaces;

const SCHEMA: Record<string, Record<string, string[]>> = %SCHEMA%;

export class RPCError extends Error {
    constructor(message: string) {
        super(message);
        this.name = "RPCError";
    }
}

type Pending = { resolve: (value: any) => void; reject: (error: Error) => void };

export class NauticaRPC {
    private ws: WebSocket;
    private pending = new Map<string, Pending>();
    private nextRef = 0;

    /** Resolves once the connection is open, calls made before that wait for it */
    readonly ready: Promise<void>;

    private constructor(url: string) {
        const target = new URL(url, typeof location !== "undefined" ? location.href : undefined);
        if (target.protocol === "http:") target.protocol = "ws:";
        else if (target.protocol === "https:") target.protocol = "wss:";

        const ws = new WebSocket(target.toString());
        this.ws = ws;
        this.ready = new Promise((resolve, reject) => {
            ws.onopen = () => resolve();
            ws.onerror = () => reject(new RPCError(`Unable to connect to ${target}`));
        });
        this.ready.catch(() => {}); //failures surface through Connect() or the calls themselves

        ws.onmessage = (e) => this.onMessage(e);
        ws.onclose = () => this.rejectAll("Connection closed");

        for (const [namespace, funcs] of Object.entries(SCHEMA)) {
            const ns: Record<string, (params?: Record<string, unknown>) => Promise<any>> = {};
            for (const [func, positional] of Object.entries(funcs)) {
                ns[func] = (params = {}) => {
                    const args = positional.map((name) => params[name]);
                    const kwargs = Object.fromEntries(
                        Object.entries(params).filter(([k, v]) => !positional.includes(k) && v !== undefined)
                    );
                    return this.call(namespace, func, args, kwargs);
                };
            }
            (this as any)[namespace] = ns;
        }
    }

    /** Connects to the RPC endpoint and waits for it to open, relative paths are resolved against the current page */
    static async Connect(url: string): Promise<RPCClient> {
        const client = NauticaRPC.Create(url);
        await client.ready;
        return client;
    }

    /** Same as Connect() but returns immediately, for places where top-level await isn't allowed (e.g. Svelte components) */
    static Create(url: string): RPCClient {
        return new NauticaRPC(url) as RPCClient;
    }

    /** Calls a function by name, prefer the typed namespaces instead */
    async call(namespace: string, func: string, args: unknown[] = [], kwargs: Record<string, unknown> = {}): Promise<any> {
        await this.ready;
        if (this.ws.readyState !== WebSocket.OPEN) throw new RPCError("Connection is not open");

        const ref = `ref${++this.nextRef}`;
        return new Promise((resolve, reject) => {
            this.pending.set(ref, { resolve, reject });
            this.ws.send(JSON.stringify({ id: "call", data: { ref, namespace, func, args, kwargs } }));
        });
    }

    close(): void {
        this.ws.close();
    }

    private onMessage(e: MessageEvent): void {
        const { id, data } = JSON.parse(e.data);

        //errors without a ref can't be traced back to a call, so fail everything in flight
        if (!data?.ref) {
            if (id === "error") this.rejectAll(data?.details ?? "Unknown error");
            return;
        }

        const pending = this.pending.get(data.ref);
        if (!pending) return;
        this.pending.delete(data.ref);

        if (id === "error") pending.reject(new RPCError(data.details));
        else pending.resolve(data.output);
    }

    private rejectAll(reason: string): void {
        for (const p of this.pending.values()) p.reject(new RPCError(reason));
        this.pending.clear();
    }
}
"""
