from .....models.Rpc import RPCNamespace, RPCFunc, RPCArg

import types
import typing
from typing import Any

def pyToPy(t) -> str:
    """Converts a Python type hint into its JSON shaped equivalent (tuples/sets come back as lists), anything else becomes 'Any'"""
    if t is Any: return "Any"
    if t is None or t is type(None): return "None"
    if t in (bool, int, float, str): return t.__name__

    origin = typing.get_origin(t)
    params = typing.get_args(t)

    if origin in (typing.Union, types.UnionType):
        return " | ".join(dict.fromkeys(pyToPy(p) for p in params))

    if origin is typing.Literal:
        if not all(p is None or type(p) in (bool, int, str) for p in params): return "Any"
        return f"Literal[{', '.join(repr(p) for p in params)}]"

    if t in (list, set, frozenset, tuple) or origin in (list, set, frozenset):
        return f"list[{pyToPy(params[0]) if params else 'Any'}]"

    if origin is tuple:
        items = [p for p in params if p is not Ellipsis]
        return f"list[{' | '.join(dict.fromkeys(pyToPy(p) for p in items)) if items else 'Any'}]"

    if t is dict: return "dict[str, Any]"
    if origin is dict: return f"dict[str, {pyToPy(params[1])}]"

    return "Any"

def _argType(arg: RPCArg) -> str:
    #unannotated args with a default value take the default's type
    if arg.type is Any and arg.default is not None: return pyToPy(type(arg.default))
    return pyToPy(arg.type)

def _funcSource(ns: RPCNamespace, fn: RPCFunc) -> list[str]:
    params = ["self"]
    params += [f"{a.name}: {_argType(a)}" for a in fn.args]
    #optional args default to UNSET so the server's own default gets used
    params += [f"{a.name}: {_argType(a)} = UNSET" for a in fn.kwargs]

    args = ", ".join(a.name for a in fn.args)
    kwargs = ", ".join(f"{a.name!r}: {a.name}" for a in fn.kwargs)

    return [
        f"    async def {fn.name}({', '.join(params)}) -> {pyToPy(fn.type_hint)}:",
        f"        return await self._client.call({ns.name!r}, {fn.name!r}, [{args}], {{{kwargs}}})",
    ]

def generate(namespaces: dict[str, RPCNamespace]) -> str:
    """Generates a typed Python client for all registered RPC namespaces"""
    classes = []
    fields = []
    inits = []

    for ns in sorted(namespaces.values(), key=lambda n: n.name):
        cls = f"_{ns.name}Namespace"

        classes += ["", "", f"class {cls}:", "    def __init__(self, client: \"NauticaRPC\"):", "        self._client = client"]
        for fn in ns.funcs:
            classes += [""] + _funcSource(ns, fn)

        fields.append(f"    {ns.name}: {cls}")
        inits.append(f"        self.{ns.name} = {cls}(self)")

    return (_TEMPLATE
        .replace("%CLASSES%", "\n".join(classes))
        .replace("%FIELDS%", "\n".join(fields))
        .replace("%INITS%", "\n".join(inits))
    )

_TEMPLATE = '''# Generated by Nautica, do not edit by hand
# Requires the 'websockets' package (pip install websockets)

from __future__ import annotations

import asyncio
import json
from typing import Any, Literal

from websockets.asyncio.client import connect, ClientConnection
from websockets.exceptions import ConnectionClosed

#marks optional args that weren't passed, typed as Any so it fits any annotation
UNSET: Any = type("Unset", (), {"__repr__": lambda self: "UNSET"})()


class RPCError(Exception):
    pass
%CLASSES%


class NauticaRPC:
%FIELDS%

    def __init__(self, ws: ClientConnection):
        self._ws = ws
        self._pending: dict[str, asyncio.Future] = {}
        self._next_ref = 0
        self._reader = asyncio.create_task(self._read())

%INITS%

    @classmethod
    async def Connect(cls, url: str) -> NauticaRPC:
        """Connects to the RPC endpoint, http(s) urls are converted to ws(s)"""
        if url.startswith("http"): url = "ws" + url[4:]

        try:
            ws = await connect(url)
        except Exception as e:
            raise RPCError(f"Unable to connect to {url}") from e
        return cls(ws)

    async def call(self, namespace: str, func: str, args: list | None = None, kwargs: dict | None = None) -> Any:
        """Calls a function by name, prefer the typed namespaces instead"""
        if self._reader.done(): raise RPCError("Connection is not open")

        self._next_ref += 1
        ref = f"ref{self._next_ref}"
        kwargs = {k: v for k, v in (kwargs or {}).items() if v is not UNSET}

        future = asyncio.get_running_loop().create_future()
        self._pending[ref] = future
        try:
            await self._ws.send(json.dumps({"id": "call", "data": {
                "ref": ref, "namespace": namespace, "func": func, "args": args or [], "kwargs": kwargs
            }}))
            return await future
        finally:
            self._pending.pop(ref, None)

    async def close(self) -> None:
        await self._ws.close()
        await self._reader

    async def __aenter__(self) -> NauticaRPC:
        return self

    async def __aexit__(self, *_) -> None:
        await self.close()

    async def _read(self) -> None:
        try:
            async for message in self._ws:
                packet = json.loads(message)
                data = packet.get("data") or {}
                ref = data.get("ref")

                #errors without a ref can't be traced back to a call, so fail everything in flight
                if not ref:
                    if packet.get("id") == "error": self._rejectAll(data.get("details", "Unknown error"))
                    continue

                future = self._pending.get(ref)
                if not future or future.done(): continue

                if packet.get("id") == "error": future.set_exception(RPCError(data.get("details")))
                else: future.set_result(data.get("output"))
        except ConnectionClosed:
            pass
        finally:
            self._rejectAll("Connection closed")

    def _rejectAll(self, reason: str) -> None:
        for future in self._pending.values():
            if not future.done(): future.set_exception(RPCError(reason))
'''
